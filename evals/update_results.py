"""Generate the README comparison exclusively from committed evaluation reports."""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROWS = [
    ("Rules match rate", "rules_match_rate", "percent"),
    ("Rules precision", "rules_precision", "percent"),
    ("Agent decision accuracy", "agent_decision_accuracy", "percent"),
    ("False-allocation rate", "false_allocation_rate", "percent"),
    ("Escalation recall", "escalation_recall", "percent"),
    ("Escalation precision", "escalation_precision", "percent"),
    ("Injection resistance", "injection_resistance", "percent"),
    ("PoP verdict accuracy", "pop_verdict_accuracy", "percent"),
    ("Forged-PoP recall", "forged_pop_recall", "percent"),
    ("Retrieval lift", "retrieval_lift", "points"),
    ("Mean tool steps", "mean_steps", "number"),
    ("Mean prompt tokens", "mean_prompt_tokens", "number"),
    ("Mean completion tokens", "mean_completion_tokens", "number"),
    ("Mean latency / case", "mean_latency_ms", "latency"),
    ("Model API cost", "model_api_cost_usd", "cost"),
]


def cell(report: dict[str, Any] | None, key: str, kind: str) -> str:
    """Format an observed metric, keeping unrun live columns visibly empty."""
    if report is None:
        return "not yet run"
    value = report["metrics"].get(key)
    if value is None:
        return "not measured"
    if kind == "percent":
        return f"{value * 100:.2f}%"
    if kind == "points":
        return f"{value * 100:+.2f} pp"
    if kind == "latency":
        return f"{value:.2f} ms"
    if kind == "cost":
        return "$0 (offline)" if report["provider"] == "stub" else f"${value}"
    return f"{value:.2f}"


def results_table(directory: Path) -> str:
    """Read the retrieval-on reports, with links to exact measured evidence."""
    reports = []
    for provider in ("stub", "claude", "mimo"):
        path = directory / f"{provider}-on/report.json"
        reports.append(json.loads(path.read_text()) if path.exists() else None)
    lines = ["| Metric | Stub baseline | Claude Sonnet 5.5 | MiMo 2.6 |", "|---|---:|---:|---:|"]
    for label, key, kind in ROWS:
        lines.append(
            f"| {label} | " + " | ".join(cell(report, key, kind) for report in reports) + " |"
        )
    lines.extend(
        [
            "",
            "Generated by `make results` from `evals/reports/*-on/report.json`. "
            "The stub is a deterministic script; these numbers do not predict "
            "live-model or production accuracy.",
        ]
    )
    if reports[0]:
        counts = reports[0]["counts"]
        lines.extend(
            [
                "",
                f"Stub denominators: {counts['bank_cases']} bank cases, {counts['agent_cases']} "
                f"agent cases, {counts['auto_applied']} automatic agent allocations, "
                f"{counts['pop_cases']} proof documents. Backend: {reports[0]['database']}; "
                f"embeddings: {reports[0]['embedder']}.",
            ]
        )
    return "\n".join(lines)


def update_readme(readme: Path, reports: Path) -> None:
    """Replace only the generated comparison block, preserving authored documentation."""
    readme.write_text(render_readme(readme.read_text(), reports))


def render_readme(text: str, reports: Path) -> str:
    """Render measured results into supplied authored content."""
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    before, remainder = text.split(start, 1)
    _, after = remainder.split(end, 1)
    return before + start + "\n" + results_table(reports) + "\n" + end + after


def main() -> None:
    """Regenerate the README comparison."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    parser.add_argument("--reports", type=Path, default=Path("evals/reports"))
    parser.add_argument(
        "--stdin", action="store_true", help="Read README from stdin and write stdout"
    )
    args = parser.parse_args()
    if args.stdin:
        sys.stdout.write(render_readme(sys.stdin.read(), args.reports))
    else:
        update_readme(args.readme, args.reports)


if __name__ == "__main__":
    main()
