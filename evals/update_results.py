"""Generate a detailed results summary from committed evaluation evidence."""

import argparse
import json
import sys
from pathlib import Path

from evals.export_evidence import Report


def results_table(directory: Path) -> str:
    """Keep the baseline and measured live runs explicit, without empty provider columns."""
    report = Report.model_validate_json(
        (directory / "stub-on/report.json").read_bytes()
    ).model_dump(mode="json")
    counts, metrics = report["counts"], report["metrics"]
    invariants = "Passed" if report["gates"]["safety_invariants"] else "Failed"
    lines = [
        f"**Synthetic dataset:** {counts['bank_cases']} bank cases, "
        f"{counts['agent_cases']} agent investigations and {counts['pop_cases']} proof documents.",
        "",
        "| Check | Scripted baseline |",
        "|---|---:|",
        f"| Wrong automatic allocations | {counts['wrong_auto_applied']} / "
        f"{counts['auto_applied']} ({metrics['false_allocation_rate']:.2%}) |",
        f"| Escalation recall | {metrics['escalation_recall']:.2%} |",
        f"| Prompt-injection resistance | {metrics['injection_resistance']:.2%} "
        f"({report['scenarios']['injection']['total']} attempts) |",
        f"| Proof-verdict accuracy | {metrics['pop_verdict_accuracy']:.2%} "
        f"({counts['pop_cases']} documents) |",
        f"| Ledger safety invariants | {invariants} "
        f"({len(report['invariant_errors'])} violations) |",
        "",
        "Generated by `make results` from `evals/reports/stub-on/report.json`.",
    ]
    live_paths = [
        directory / f"{provider}-{mode}/report.json"
        for provider in ("claude", "mimo")
        for mode in ("on", "off")
    ]
    live_reports = [(path, json.loads(path.read_text())) for path in live_paths if path.is_file()]
    live_reports = [
        (path, value)
        for path, value in live_reports
        if value.get("evaluation_scope", "full") == "full"
    ]
    if live_reports:
        lines.extend(
            [
                "",
                "**Live evaluations** (synthetic data; hash retrieval is nonsemantic):",
                "",
                "| Run | Agent accuracy | Incomplete | API cost (USD) | Gates |",
                "|---|---:|---:|---:|---|",
            ]
        )
        for path, value in live_reports:
            Report.model_validate_json(json.dumps(value))
            mode = "on" if value["retrieval_enabled"] else "off"
            metrics = value["metrics"]
            cost = metrics["model_api_cost_usd"]
            cost_text = f"${cost:.6f}" if cost is not None else "Not measured"
            lines.append(
                f"| [{value['model']} · retrieval {mode}]({path.parent.as_posix()}/report.md) "
                f"| {metrics['agent_decision_accuracy']:.2%} "
                f"| {metrics['incomplete_investigations']} / {value['counts']['agent_cases']} "
                f"| {cost_text} | {'Passed' if value['passed'] else 'Failed'} |"
            )
        lines.extend(
            [
                "",
                "Failed gates remain visible. Zero wrong allocations with no automatic "
                "allocations is not evidence of allocation accuracy. See each report for "
                "denominators, routing and failure traces.",
            ]
        )
    else:
        lines.extend(["", "No full live-provider evaluation is published."])
    return "\n".join(lines)


def update_document(document: Path, reports: Path) -> None:
    """Replace only the generated summary, preserving authored documentation."""
    document.write_text(render_document(document.read_text(), reports))


def render_document(text: str, reports: Path) -> str:
    """Render measured results into supplied authored content."""
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    before, remainder = text.split(start, 1)
    _, after = remainder.split(end, 1)
    return before + start + "\n" + results_table(reports) + "\n" + end + after


def main() -> None:
    """Regenerate the detailed evaluation results document."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--document", type=Path, default=Path("EVALUATION_RESULTS.md"))
    parser.add_argument("--reports", type=Path, default=Path("evals/reports"))
    parser.add_argument(
        "--stdin", action="store_true", help="Read document from stdin and write stdout"
    )
    args = parser.parse_args()
    if args.stdin:
        sys.stdout.write(render_document(sys.stdin.read(), args.reports))
    else:
        update_document(args.document, args.reports)


if __name__ == "__main__":
    main()
